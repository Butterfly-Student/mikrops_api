package model

import (
	"time"

	"github.com/google/uuid"
	"gorm.io/gorm"
)

// InvoiceStatus represents invoice status
type InvoiceStatus string

const (
	InvoiceStatusDraft     InvoiceStatus = "draft"
	InvoiceStatusSent      InvoiceStatus = "sent"
	InvoiceStatusPartial   InvoiceStatus = "partial"
	InvoiceStatusPaid      InvoiceStatus = "paid"
	InvoiceStatusOverdue   InvoiceStatus = "overdue"
	InvoiceStatusCancelled InvoiceStatus = "cancelled"
	InvoiceStatusRefunded  InvoiceStatus = "refunded"
)

// PaymentStatus represents payment status of invoice
type PaymentStatus string

const (
	PaymentStatusUnpaid   PaymentStatus = "unpaid"
	PaymentStatusPartial  PaymentStatus = "partial"
	PaymentStatusPaid     PaymentStatus = "paid"
	PaymentStatusOverpaid PaymentStatus = "overpaid"
)

// InvoiceType represents type of invoice
type InvoiceType string

const (
	InvoiceTypeRecurring     InvoiceType = "recurring"
	InvoiceTypeInstallation  InvoiceType = "installation"
	InvoiceTypeAdditional    InvoiceType = "additional"
	InvoiceTypeRefund        InvoiceType = "refund"
)

// Invoice represents customer invoice/bill
type Invoice struct {
	ID            uuid.UUID      `gorm:"type:uuid;primaryKey;default:gen_random_uuid()" json:"id"`
	InvoiceNumber string         `gorm:"size:50;uniqueIndex;not null" json:"invoice_number" validate:"required"`
	CustomerID    uuid.UUID      `gorm:"type:uuid;not null" json:"customer_id" validate:"required"`
	Customer      *Customer      `gorm:"foreignKey:CustomerID;constraint:OnDelete:RESTRICT" json:"customer,omitempty"`

	// Billing Period
	BillingPeriodStart time.Time `gorm:"type:date;not null" json:"billing_period_start" validate:"required"`
	BillingPeriodEnd   time.Time `gorm:"type:date;not null" json:"billing_period_end" validate:"required"`
	BillingMonth       *int      `json:"billing_month" validate:"omitempty,min=1,max=12"`
	BillingYear        *int      `json:"billing_year"`

	// Dates
	IssueDate       time.Time  `gorm:"type:date;not null;default:CURRENT_DATE" json:"issue_date"`
	DueDate         time.Time  `gorm:"type:date;not null" json:"due_date" validate:"required"`
	PaymentDeadline *time.Time `json:"payment_deadline"`

	// Amounts
	Subtotal       float64 `gorm:"type:decimal(12,2);not null;default:0" json:"subtotal"`
	TaxAmount      float64 `gorm:"type:decimal(12,2);not null;default:0" json:"tax_amount"`
	DiscountAmount float64 `gorm:"type:decimal(12,2);default:0" json:"discount_amount"`
	LateFee        float64 `gorm:"type:decimal(12,2);default:0" json:"late_fee"`
	TotalAmount    float64 `gorm:"type:decimal(12,2);not null" json:"total_amount" validate:"required"`
	PaidAmount     float64 `gorm:"type:decimal(12,2);default:0" json:"paid_amount"`
	Balance        float64 `gorm:"type:decimal(12,2);->;default:0" json:"balance"` // computed column

	// Status
	Status        InvoiceStatus  `gorm:"size:20;not null;default:draft" json:"status"`
	PaymentStatus *PaymentStatus `gorm:"size:20" json:"payment_status"`

	// Payment Information
	PaymentDate   *time.Time `json:"payment_date"`
	PaymentMethod *string    `gorm:"size:20" json:"payment_method"`

	// Additional
	InvoiceType        InvoiceType `gorm:"size:20;default:recurring" json:"invoice_type"`
	IsAutoGenerated    *bool       `gorm:"default:true" json:"is_auto_generated"`
	ReminderSentCount  *int        `gorm:"default:0" json:"reminder_sent_count"`
	LastReminderSent   *time.Time  `json:"last_reminder_sent"`

	Notes         *string `gorm:"type:text" json:"notes"`
	InternalNotes *string `gorm:"type:text" json:"internal_notes"` // not shown in PDF

	// Relations
	Items []InvoiceItem `gorm:"foreignKey:InvoiceID" json:"items,omitempty"`

	CreatedBy *uuid.UUID `gorm:"type:uuid" json:"created_by"`
	UpdatedBy *uuid.UUID `gorm:"type:uuid" json:"updated_by"`
	CreatedAt time.Time  `json:"created_at"`
	UpdatedAt time.Time  `json:"updated_at"`
	DeletedAt gorm.DeletedAt `gorm:"index" json:"-"`
}

// TableName specifies the table name for Invoice
func (Invoice) TableName() string {
	return "invoices"
}

// InvoiceItemType represents type of invoice item
type InvoiceItemType string

const (
	InvoiceItemTypeSubscription InvoiceItemType = "subscription"
	InvoiceItemTypeInstallation InvoiceItemType = "installation"
	InvoiceItemTypeEquipment    InvoiceItemType = "equipment"
	InvoiceItemTypeOther        InvoiceItemType = "other"
)

// InvoiceItem represents line item in invoice
type InvoiceItem struct {
	ID          uuid.UUID        `gorm:"type:uuid;primaryKey;default:gen_random_uuid()" json:"id"`
	InvoiceID   uuid.UUID        `gorm:"type:uuid;not null" json:"invoice_id" validate:"required"`
	ItemType    *InvoiceItemType `gorm:"size:20" json:"item_type"`
	Description string           `gorm:"size:255;not null" json:"description" validate:"required"`

	ProfileID *uuid.UUID        `gorm:"type:uuid" json:"profile_id"`
	Profile   *BandwidthProfile `gorm:"foreignKey:ProfileID;constraint:OnDelete:SET NULL" json:"profile,omitempty"`

	Quantity  int     `gorm:"not null;default:1" json:"quantity" validate:"required,min=1"`
	UnitPrice float64 `gorm:"type:decimal(12,2);not null" json:"unit_price" validate:"required"`
	Subtotal  float64 `gorm:"type:decimal(12,2);not null" json:"subtotal" validate:"required"`
	TaxRate   float64 `gorm:"type:decimal(5,4);default:0" json:"tax_rate"`
	TaxAmount float64 `gorm:"type:decimal(12,2);default:0" json:"tax_amount"`
	Total     float64 `gorm:"type:decimal(12,2);not null" json:"total" validate:"required"`

	// Proration
	IsProrated           *bool    `gorm:"default:false" json:"is_prorated"`
	ProrationDays        *int     `json:"proration_days"`
	ProrationPercentage  *float64 `gorm:"type:decimal(5,2)" json:"proration_percentage"`

	SortOrder *int      `gorm:"default:0" json:"sort_order"`
	CreatedAt time.Time `json:"created_at"`
}

// TableName specifies the table name for InvoiceItem
func (InvoiceItem) TableName() string {
	return "invoice_items"
}

