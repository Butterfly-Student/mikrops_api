// ToModel converts input to model
func (i *InvoiceInput) ToModel() *Invoice {
	invoice := &Invoice{
		InvoiceNumber:      i.InvoiceNumber,
		CustomerID:         i.CustomerID,
		BillingPeriodStart: i.BillingPeriodStart,
		BillingPeriodEnd:   i.BillingPeriodEnd,
		BillingMonth:       i.BillingMonth,
		BillingYear:        i.BillingYear,
		DueDate:            i.DueDate,
		PaymentDeadline:    i.PaymentDeadline,
		Subtotal:           i.Subtotal,
		TaxAmount:          i.TaxAmount,
		DiscountAmount:     i.DiscountAmount,
		LateFee:            i.LateFee,
		TotalAmount:        i.TotalAmount,
		Notes:              i.Notes,
		InternalNotes:      i.InternalNotes,
	}

	// Set issue date
	if i.IssueDate != nil {
		invoice.IssueDate = *i.IssueDate
	} else {
		invoice.IssueDate = time.Now()
	}

	// Set status
	if i.Status != nil {
		invoice.Status = InvoiceStatus(*i.Status)
	} else {
		invoice.Status = InvoiceStatusDraft
	}

	// Set invoice type
	if i.InvoiceType != nil {
		invoice.InvoiceType = InvoiceType(*i.InvoiceType)
	} else {
		invoice.InvoiceType = InvoiceTypeRecurring
	}

	// Convert items
	if len(i.Items) > 0 {
		items := make([]InvoiceItem, len(i.Items))
		for idx, item := range i.Items {
			items[idx] = *item.ToModel()
		}
		invoice.Items = items
	}

	return invoice
}

// ToModel converts input to model
func (i *InvoiceItemInput) ToModel() *InvoiceItem {
	item := &InvoiceItem{
		Description:         i.Description,
		ProfileID:           i.ProfileID,
		Quantity:            i.Quantity,
		UnitPrice:           i.UnitPrice,
		Subtotal:            i.Subtotal,
		TaxRate:             i.TaxRate,
		TaxAmount:           i.TaxAmount,
		Total:               i.Total,
		IsProrated:          i.IsProrated,
		ProrationDays:       i.ProrationDays,
		ProrationPercentage: i.ProrationPercentage,
		SortOrder:           i.SortOrder,
	}

	// Set item type
	if i.ItemType != nil {
		itemType := InvoiceItemType(*i.ItemType)
		item.ItemType = &itemType
	}

	return item
}

// IsOverdue checks if invoice is overdue
func (inv *Invoice) IsOverdue() bool {
	return time.Now().After(inv.DueDate) && inv.Balance > 0
}

// IsPaid checks if invoice is fully paid
func (inv *Invoice) IsPaid() bool {
	return inv.PaidAmount >= inv.TotalAmount
}

// GetBalance returns balance amount
func (inv *Invoice) GetBalance() float64 {
	return inv.TotalAmount - inv.PaidAmount
}

// UpdatePaymentStatus updates payment status based on paid amount
func (inv *Invoice) UpdatePaymentStatus() {
	balance := inv.GetBalance()

	if balance <= 0 {
		status := PaymentStatusPaid
		inv.PaymentStatus = &status
		inv.Status = InvoiceStatusPaid
	} else if inv.PaidAmount > 0 {
		status := PaymentStatusPartial
		inv.PaymentStatus = &status
		inv.Status = InvoiceStatusPartial
	} else {
		status := PaymentStatusUnpaid
		inv.PaymentStatus = &status
		if inv.IsOverdue() {
			inv.Status = InvoiceStatusOverdue
		}
	}
}
